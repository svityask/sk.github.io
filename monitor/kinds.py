"""Вид товара по названию: тип + основа + класс («Клей плиточный C1», «Штукатурка гипсовая»).

Нужен, чтобы сравнивать Основит с аналогами, а не со всем разделом: в «Штукатурках» лежат и гипсовые,
и цементные, и готовые полимерные — у них разная цена за кг. Вид всегда можно поправить вручную.
"""

import functools
import re

# (тип, условие). Порядок важен: первое совпадение побеждает.
_TYPES = [
    ("Клей гипсовый", (r"клей", r"гипс|гипсокартон|\bгкл\b|пазогребн|\bпгп\b")),
    ("Клей для блоков", (r"клей", r"блок|газобетон|пенобетон|газосиликат|кладк|кладоч")),
    ("Клей для теплоизоляции", (r"клей", r"утепл|теплоизол|пенопласт|пенополистир|минват|минерал\w* ват|сфтк|армир")),
    ("Клей плиточный", (r"клей", r"плит|керамогранит|кафел|мозаик|камн|камен|облицов")),
    ("Шпаклёвка", (r"шпа[кт]л",)),
    ("Штукатурка декоративная", (r"штукатур", r"декоратив|короед|\bшуба\b|барашек|мозаичн|фактурн|венецианск")),
    ("Штукатурка", (r"штукатур",)),
    ("Наливной пол", (r"наливн|самовыравн|нивелир|ровнител",)),
    ("Пескобетон", (r"пескобетон",)),
    ("Стяжка", (r"стяжк",)),
    ("Затирка", (r"затирк|фуг[аи]\b|фуговоч",)),
    ("Гидроизоляция", (r"гидроизол|обмазоч",)),
    ("Грунтовка", (r"грунт",)),
    ("Кладочная смесь", (r"кладочн|кладоч|для кладки",)),
    ("Ремонтная смесь", (r"ремонтн",)),
    ("Монтажная смесь", (r"монтажн\w* смес|анкеровоч",)),
    ("Клей", (r"\bклей",)),
    ("Цементно-песчаная смесь", (r"цементно-песчан|\bцпс\b|пескоцемент",)),
    ("Цемент", (r"\bцемент\b|\bпортландцемент",)),
    ("Герметик", (r"герметик",)),
    ("Пена монтажная", (r"\bпена\b",)),
    ("Краска", (r"краск|эмаль",)),
    # «Смесь для пола» без слов «наливной»/«ровнитель» — последней, чтобы «Грунтовка для пола» осталась грунтовкой
    ("Наливной пол", (r"смес\w* для пола|для пола",)),
]

# Что продают на литры: при фасовке «5 л (5,2 кг)» берём литры, у остальных — килограммы
LIQUID_TYPES = {"Грунтовка", "Краска", "Герметик", "Пена монтажная"}

_BASES = [
    ("гипсовая", r"гипс"),
    ("цементная", r"цемент|пескоцемент|цпс\b"),
    ("известковая", r"извест"),
    ("полимерная", r"полимер|акрил|винил|готов|паст[аообр]|латекс"),
    ("эпоксидная", r"эпоксид"),
]

_FINISH = [
    # корни, а не начало слова: «Стартолайн», «Финишсилк» — названия линеек, а не финиш/старт
    ("финишная", r"финишн|\bфиниш\b|тонкослой|отделочн"),
    ("стартовая", r"стартов|\bстарт\b|базов|толстослой|(?<!само)выравнива"),
    ("универсальная", r"универс"),
]

_TILE_CLASS = re.compile(r"(?<![a-zа-я0-9])[cс]\s?([012])(?:\s?t)?(?:\s?e)?(?:\s?s\s?[12])?(?![a-zа-я0-9])", re.I)
_GRADE = re.compile(r"(?<![a-zа-я0-9])[mм]\s?-?(100|150|200|250|300|350|400|450|500)(?![0-9])", re.I)


# скомпилированные выражения: вид распознаётся для каждого товара при каждом поиске и сборе
_TYPES_RX = [(label, tuple(re.compile(c) for c in conds)) for label, conds in _TYPES]
_BASES_RX = [(label, re.compile(rx)) for label, rx in _BASES]
_FINISH_RX = [(label, re.compile(rx)) for label, rx in _FINISH]


def _find(pairs, text):
    for label, rx in pairs:
        if rx.search(text):
            return label
    return None


def attrs(name):
    """Признаки товара: {'type', 'base', 'finish', 'grade'} — неизвестные не попадают в словарь."""
    return dict(_attrs(name or ""))  # копия: вызывающий может менять словарь, кэш — нет


@functools.lru_cache(maxsize=100_000)
def _attrs(name):
    """Признаки как кортеж пар (неизменяемый, чтобы кэшировать): названия повторяются из сбора в сбор."""
    return tuple(_parse(name).items())


def _parse(name):
    text = " " + name.lower().replace("ё", "е") + " "
    ptype = None
    for label, conds in _TYPES_RX:
        if all(c.search(text) for c in conds):
            ptype = label
            break
    if not ptype:
        return {}
    a = {"type": ptype}
    if ptype in ("Штукатурка", "Штукатурка декоративная", "Шпаклёвка", "Затирка", "Наливной пол"):
        base = _find(_BASES_RX, text)
        if base:
            a["base"] = base
    if ptype in ("Шпаклёвка", "Наливной пол"):
        fin = _find(_FINISH_RX, text)
        if fin:
            a["finish"] = fin
    if ptype == "Клей плиточный":
        m = _TILE_CLASS.search(text)
        if m:
            a["grade"] = "C" + m.group(1)
    if ptype in ("Пескобетон", "Кладочная смесь", "Стяжка", "Цемент", "Цементно-песчаная смесь"):
        m = _GRADE.search(text)
        if m:
            a["grade"] = "М" + m.group(1)
    return a


def label(a):
    if not a:
        return None
    parts = [a["type"]]
    masc = a["type"] == "Наливной пол"
    for k in ("base", "finish"):
        if a.get(k):
            parts.append(_masc(a[k]) if masc else a[k])
    if a.get("grade"):
        parts.append(a["grade"])
    return " ".join(parts)


def detect(name):
    """Вид товара строкой («Клей плиточный C1») или None."""
    return label(attrs(name))


def compatible(a, b):
    """Аналог: тот же тип и ни одного противоречащего признака (неизвестный признак не мешает)."""
    if not a or not b or a.get("type") != b.get("type"):
        return False
    return all(a[k] == b[k] for k in ("base", "finish", "grade") if a.get(k) and b.get(k))


def _masc(adj):
    """гипсовая → гипсовый (для «Наливной пол»)."""
    return re.sub(r"ая$", "ый", adj)


def pack_unit(name):
    """Какую единицу предпочесть, если в названии и кг, и л: 'л' для жидкостей, иначе 'кг'."""
    t = attrs(name).get("type")
    return "л" if t in LIQUID_TYPES else "кг"


def attrs_of(product, overrides):
    """Признаки с учётом ручной правки: (признаки, вручную?)."""
    manual = overrides.get(product["key"])
    if manual:
        return attrs(manual) or {"type": manual}, True
    return attrs(product.get("name")), False


def all_labels():
    """Подсказки для ручного выбора вида."""
    out = []
    for t, _ in _TYPES:
        out.append(t)
        if t in ("Штукатурка", "Шпаклёвка", "Затирка"):
            out += [f"{t} {b}" for b, _ in _BASES if not (t != "Затирка" and b == "эпоксидная")]
        if t == "Клей плиточный":
            out += [f"{t} C{i}" for i in range(3)]
    return out
